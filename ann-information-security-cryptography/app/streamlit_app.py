import sys
from pathlib import Path

import streamlit as st

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.crypto_system import decrypt, encrypt, key_from_hex, render  # noqa: E402

NODE_LABELS = {
    "node1": "Node 1 - alphabetic values",
    "node2": "Node 2 - non-alphabetic values",
    "node3": "Node 3 - Node 1, even positions",
    "node4": "Node 4 - Node 1, odd positions",
    "node5": "Node 5 - Node 2, even positions",
    "node6": "Node 6 - Node 2, odd positions",
    "node7": "Node 7 = Node 3 + Node 6",
    "node8": "Node 8 = Node 4 + Node 5",
}
EXAMPLE_TEXT = "Namaste India!"


def show_nodes(result: dict) -> None:
    """Show the report's hidden layer (Node 1 ... Node 8) as a table."""
    rows = [
        {
            "Node": NODE_LABELS[name],
            "Values": render(value for value, _ in pairs),
            "Original indices": ", ".join(str(index) for _, index in pairs),
        }
        for name, pairs in result["nodes"].items()
    ]
    st.table(rows)


st.set_page_config(
    page_title="ANN Information Security Demo",
    page_icon="🔐",
    layout="centered",
)

st.title("🔐 Information Security — ANN Project Demo")
st.caption("B.Sc. (Hons) Computer Science project · Educational cryptography demonstration")

st.warning(
    "Educational use only. The project algorithm is a custom XOR/rearrangement "
    "heuristic and is NOT a modern, secure cryptographic system."
)

tab_encrypt, tab_decrypt, tab_how, tab_about = st.tabs(
    ["Encrypt", "Decrypt", "How it works", "About"]
)

with tab_encrypt:
    st.subheader("Encrypt plaintext")
    plaintext = st.text_area(
        "Plaintext",
        key="plaintext_input",
        placeholder="Enter a message, e.g. Namaste India!",
        height=140,
    )

    if st.button("Encrypt", type="primary", key="encrypt_btn"):
        if not plaintext:
            st.error("Please enter plaintext.")
        else:
            st.session_state["last_result"] = encrypt(plaintext)

    result = st.session_state.get("last_result")
    if result:
        st.success("Encryption completed.")

        st.markdown("**Generated key (hex)** — share it separately from the token")
        st.code(result["key_hex"], language="text")
        st.caption("Key characters: " + render(map(ord, result["key"])))

        st.markdown("**Intermediate ciphertext** (plaintext XOR key)")
        st.code(render(result["intermediate_values"]), language="text")

        st.markdown("**Final ciphertext** (Node 7 + Node 8)")
        st.code(render(result["cipher_values"]), language="text")

        st.markdown("**Portable ciphertext token** (values + original indices, no key)")
        st.code(result["token"], language="text")

        st.download_button(
            "Download ciphertext token",
            data=result["token"],
            file_name="ciphertext.txt",
            mime="text/plain",
        )

        with st.expander("Show the eight nodes"):
            show_nodes(result)

with tab_decrypt:
    st.subheader("Decrypt a ciphertext token")
    token = st.text_area(
        "Ciphertext token",
        key="token_input",
        placeholder="Paste the token generated by the Encrypt tab.",
        height=140,
    )
    key_hex = st.text_input(
        "Key (hex)",
        key="key_hex_input",
        placeholder="Paste the hexadecimal key from the Encrypt tab.",
    )

    if st.button("Decrypt", key="decrypt_btn"):
        if not token or not key_hex:
            st.error("Ciphertext token and key are both required.")
        else:
            try:
                recovered = decrypt(token.strip(), key_from_hex(key_hex))
            except ValueError as exc:
                st.error(str(exc))
            else:
                st.success("Decryption completed.")
                st.text_area("Recovered plaintext", value=recovered, height=120)
                st.caption(
                    "The scheme has no authentication: a wrong key gives unreadable "
                    "text instead of an error."
                )

with tab_how:
    st.subheader("Project algorithm")
    st.markdown(
        """
        1. **Key generation** — repeat the plaintext to 8 characters; each key
           character is the absolute difference between neighbouring characters'
           ASCII/Unicode values (the first one wraps around to the last).
        2. **Input layer** — XOR each plaintext character with the cyclic key.
           The result is the *intermediate ciphertext*.
        3. **Hidden layer** — split the values into alphabetic (Node 1) and
           non-alphabetic (Node 2); split each into even/odd positions
           (Nodes 3–6); join Node 3 + Node 6 = Node 7 and Node 4 + Node 5 = Node 8.
        4. **Output layer** — Node 7 + Node 8 is the *final ciphertext*. Every value
           keeps its original index.
        5. **Decryption** — sort the values by index, then XOR with the key again.
        """
    )
    st.info(
        "The 'neurons' are fixed processing nodes; nothing is trained. The report "
        "presents this feed-forward node structure as its symmetric-key design."
    )

    example = encrypt(EXAMPLE_TEXT)
    st.markdown(f"**Live example:** `{EXAMPLE_TEXT}`")
    st.code(
        f"key (hex)          : {example['key_hex']}\n"
        f"intermediate       : {render(example['intermediate_values'])}\n"
        f"final ciphertext   : {render(example['cipher_values'])}",
        language="text",
    )
    show_nodes(example)

